using MediSlot.Application.Common;
using MediSlot.Application.DTOs.Slots;
using MediSlot.Application.Interfaces;
using MediSlot.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace MediSlot.Infrastructure.Jobs;

public class SlotGenerationJob
{
    private readonly AppDbContext _db;
    private readonly ISlotService _slots;
    private readonly ClinicSettings _clinic;
    private readonly TimeZoneInfo _tz;
    private readonly ILogger<SlotGenerationJob> _logger;

    public SlotGenerationJob(
        AppDbContext db,
        ISlotService slots,
        IOptions<ClinicSettings> options,
        ILogger<SlotGenerationJob> logger)
    {
        _db = db;
        _slots = slots;
        _clinic = options.Value;
        _tz = TimeZoneInfo.FindSystemTimeZoneById(_clinic.TimeZoneId);
        _logger = logger;
    }

    public async Task RunAsync()
    {
        var today = DateOnly.FromDateTime(TimeZoneInfo.ConvertTimeFromUtc(DateTime.UtcNow, _tz));
        var days = Math.Clamp(_clinic.AutoGenerateDays, 1, _clinic.MaxGenerateDays);
        var request = new GenerateSlotsRequest(today, today.AddDays(days - 1));

        // Fakt active doctors jyanna schedule ahe (schedule nasalela doctor skip)
        var doctorIds = await _db.Doctors
            .AsNoTracking()
            .Where(d => d.User.IsActive && d.Schedules.Any())
            .Select(d => d.Id)
            .ToListAsync();

        _logger.LogInformation(
            "Slot generation started for {DoctorCount} doctors, {From} to {To}",
            doctorIds.Count, request.FromDate, request.ToDate);

        int created = 0, failed = 0;

        foreach (var doctorId in doctorIds)
        {
            try
            {
                var result = await _slots.GenerateAsync(doctorId, request);
                created += result.Created;
            }
            catch (Exception ex)
            {
                failed++;
                _logger.LogError(ex, "Slot generation failed for doctor {DoctorId}", doctorId);

                // Fail zalela save DbContext madhe adakun rahto, to saaf kara
                // nahi tar pudhchya doctor cha SaveChanges pan fail hoil
                _db.ChangeTracker.Clear();
            }
        }

        _logger.LogInformation(
            "Slot generation finished: {Created} slots created, {Failed} doctors failed",
            created, failed);

        // Fail zala tar job la fail mark kara, mhanje Hangfire retry karel (job idempotent ahe, retry safe)
        if (failed > 0)
            throw new InvalidOperationException($"Slot generation failed for {failed} doctor(s). See logs.");
    }
}