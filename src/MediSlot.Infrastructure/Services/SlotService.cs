using MediSlot.Application.Common;
using MediSlot.Application.DTOs.Slots;
using MediSlot.Application.Interfaces;
using MediSlot.Domain.Entities;
using MediSlot.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Options;

namespace MediSlot.Infrastructure.Services;

public class SlotService : ISlotService
{
    private readonly AppDbContext _db;
    private readonly ClinicSettings _clinic;
    private readonly TimeZoneInfo _tz;

    public SlotService(AppDbContext db, IOptions<ClinicSettings> options)
    {
        _db = db;
        _clinic = options.Value;
        _tz = TimeZoneInfo.FindSystemTimeZoneById(_clinic.TimeZoneId);
    }

    // Server cha UTC nahi, clinic chi local vel (Pune = IST)
    private DateTime ClinicNow => TimeZoneInfo.ConvertTimeFromUtc(DateTime.UtcNow, _tz);

    public async Task<GenerateSlotsResponse> GenerateForUserAsync(
        int userId, GenerateSlotsRequest request, CancellationToken ct = default)
    {
        var doctor = await _db.Doctors
            .FirstOrDefaultAsync(d => d.UserId == userId && d.User.IsActive, ct)
            ?? throw new NotFoundException("Doctor profile not found.");

        return await GenerateAsync(doctor.Id, request, ct);
    }

    public async Task<GenerateSlotsResponse> GenerateAsync(
        int doctorId, GenerateSlotsRequest request, CancellationToken ct = default)
    {
        if (!await _db.Doctors.AnyAsync(d => d.Id == doctorId && d.User.IsActive, ct))
            throw new NotFoundException("Doctor not found.");

        var today = DateOnly.FromDateTime(ClinicNow);

        if (request.FromDate < today)
            throw new BadRequestException("FromDate cannot be in the past.");

        var days = request.ToDate.DayNumber - request.FromDate.DayNumber + 1;
        if (days > _clinic.MaxGenerateDays)
            throw new BadRequestException($"You can generate slots for at most {_clinic.MaxGenerateDays} days at a time.");

        var schedules = await _db.DoctorSchedules
            .AsNoTracking()
            .Where(s => s.DoctorId == doctorId)
            .ToListAsync(ct);

        if (schedules.Count == 0)
            throw new BadRequestException("Doctor has no schedule. Add a schedule first.");

        // Aadhich ase slots (date + start time) aadhich ghetat, mhanje duplicate banvat nahit
        var existing = (await _db.Slots
                .AsNoTracking()
                .Where(s => s.DoctorId == doctorId && s.Date >= request.FromDate && s.Date <= request.ToDate)
                .Select(s => new { s.Date, s.StartTime })
                .ToListAsync(ct))
            .Select(s => (s.Date, s.StartTime))
            .ToHashSet();

        var newSlots = new List<Slot>();
        var alreadyExisting = 0;

        for (var date = request.FromDate; date <= request.ToDate; date = date.AddDays(1))
        {
            foreach (var schedule in schedules.Where(s => s.DayOfWeek == date.DayOfWeek))
            {
                var totalMinutes = (int)(schedule.EndTime - schedule.StartTime).TotalMinutes;

                for (var offset = 0; offset + schedule.SlotDurationMins <= totalMinutes; offset += schedule.SlotDurationMins)
                {
                    var start = schedule.StartTime.AddMinutes(offset);

                    if (existing.Contains((date, start)))
                    {
                        alreadyExisting++;
                        continue;
                    }

                    newSlots.Add(new Slot
                    {
                        DoctorId = doctorId,
                        Date = date,
                        StartTime = start,
                        EndTime = start.AddMinutes(schedule.SlotDurationMins),
                        IsBooked = false
                    });
                }
            }
        }

        if (newSlots.Count > 0)
        {
            _db.Slots.AddRange(newSlots);

            try
            {
                await _db.SaveChangesAsync(ct);
            }
            catch (DbUpdateException)
            {
                // Unique index (Doctor + Date + StartTime): doghe ek veli generate kele tar
                throw new ConflictException("Slots are being generated by another request. Please try again.");
            }
        }

        return new GenerateSlotsResponse(request.FromDate, request.ToDate, newSlots.Count, alreadyExisting);
    }

    public async Task<List<SlotResponse>> GetAvailableAsync(
        int doctorId, DateOnly date, CancellationToken ct = default)
    {
        if (!await _db.Doctors.AnyAsync(d => d.Id == doctorId && d.User.IsActive, ct))
            throw new NotFoundException("Doctor not found.");

        var now = ClinicNow;
        var today = DateOnly.FromDateTime(now);

        if (date < today)
            throw new BadRequestException("Date cannot be in the past.");

        var query = _db.Slots
            .AsNoTracking()
            .Where(s => s.DoctorId == doctorId && s.Date == date && !s.IsBooked);

        // Aajchya divashi, nighun geleli vel dakhavaychi nahi
        if (date == today)
        {
            var currentTime = TimeOnly.FromDateTime(now);
            query = query.Where(s => s.StartTime > currentTime);
        }

        return await query
            .OrderBy(s => s.StartTime)
            .Select(s => new SlotResponse(s.Id, s.Date, s.StartTime, s.EndTime))
            .ToListAsync(ct);
    }
}